// Builds the chat's built-in sticker pack from Microsoft's Fluent Emoji Animated (MIT,
// github.com/microsoft/fluentui-emoji-animated): downloads each animated PNG and converts it to a
// small animated WebP (160 px) with the ffmpeg the project already ships. Writes
// public/stickers/fluent/*.webp and shared/stickers.js.   node scripts/fetch-stickers.mjs
import { execFile } from "node:child_process";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { promisify } from "node:util";
import ffmpeg from "@ffmpeg-installer/ffmpeg";

const run = promisify(execFile);
const PICKS = [
  "Sparkling heart", "Two hearts", "Revolving hearts", "Heart with ribbon", "Growing heart", "Beating heart",
  "Heart hands", "Love letter", "Face blowing a kiss", "Smiling face with hearts", "Pleading face", "Hugging face",
  "People hugging", "Loudly crying face", "Face holding back tears", "Rolling on the floor laughing", "Star-struck",
  "Sleepy face", "Smiling cat with heart-eyes", "Kissing cat", "Cat face", "Crying cat", "Teddy bear", "Butterfly",
  "Rainbow", "Glowing star", "Shooting star", "Full moon face", "Sun with face", "Unicorn", "Birthday cake",
  "Teacup without handle", "Woman fairy", "Ghost",
];
const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const out = path.resolve("public/stickers/fluent");
await mkdir(out, { recursive: true });
const work = await mkdtemp(path.join(tmpdir(), "stickers-"));
const made = [];
try {
  for (const name of PICKS) {
    const file = `${name.toLowerCase().replace(/ /g, "_").replace(/-/g, "_")}_animated.png`;
    const url = `https://media.githubusercontent.com/media/microsoft/fluentui-emoji-animated/main/assets/${encodeURIComponent(name)}/animated/${file}`;
    const response = await fetch(url);
    if (!response.ok) {
      console.warn("skipped", name, response.status);
      continue;
    }
    const source = path.join(work, `${slug(name)}.png`);
    await writeFile(source, Buffer.from(await response.arrayBuffer()));
    const target = path.join(out, `${slug(name)}.webp`);
    await run(ffmpeg.path, ["-hide_banner", "-loglevel", "error", "-y", "-i", source, "-vf", "fps=15,scale=128:128:flags=lanczos", "-c:v", "libwebp", "-lossless", "0", "-q:v", "42", "-compression_level", "6", "-loop", "0", "-an", target]);
    made.push({ id: slug(name), label: name.toLowerCase(), url: `/stickers/fluent/${slug(name)}.webp` });
    console.log("made", slug(name));
  }
} finally {
  await rm(work, { recursive: true, force: true });
}
await writeFile(
  path.resolve("shared/stickers.js"),
  `// Generated by scripts/fetch-stickers.mjs. Fluent Emoji Animated © Microsoft, MIT licence.\nexport const STICKER_PACKS = ${JSON.stringify([{ id: "fluent", label: "cute & animated", credit: "Fluent Emoji Animated © Microsoft (MIT)", stickers: made }], null, 2)};\n`,
);
console.log(`${made.length} stickers`);
