// Writes src/shared/opening/wordmark.js: the launch image's "kiriya" (scripts/make-app-icon.mjs,
// art(2732, { widthShare: 0.3 })) as path data, so the opening's first frame lines up with the
// native splash exactly. Same font (Parisienne, SIL OFL), same layout maths, same stroke.
//   node src/shared/opening/make-wordmark.mjs
import { writeFile } from "node:fs/promises";
import path from "node:path";
import * as fontkit from "fontkit";

const font = fontkit.openSync(path.resolve("public/fonts/parisienne-400.woff2"));
const run = font.layout("kiriya");
let x = 0;
const glyphs = [];
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
run.glyphs.forEach((glyph, i) => {
  const p = run.positions[i];
  const box = glyph.bbox;
  const ox = x + p.xOffset, oy = p.yOffset;
  if (Number.isFinite(box.minX)) {
    minX = Math.min(minX, ox + box.minX); maxX = Math.max(maxX, ox + box.maxX);
    minY = Math.min(minY, oy + box.minY); maxY = Math.max(maxY, oy + box.maxY);
  }
  glyphs.push({ ox, oy, d: glyph.path.toSVG(), box: { minX: ox + box.minX, maxX: ox + box.maxX, minY: oy + box.minY, maxY: oy + box.maxY } });
  x += p.xAdvance;
});
const size = 2732, widthShare = 0.3;
const inkW = maxX - minX, inkH = maxY - minY;
const scale = (size * widthShare) / inkW;
const cx = size / 2, cy = size / 2;
const tx = cx - (minX + inkW / 2) * scale;
const ty = cy + (minY + inkH / 2) * scale;
const unit = (size * widthShare) / (1024 * 0.74);
const sx = cx + (inkW / 2) * scale + 20 * unit, sy = cy - (inkH / 2) * scale + 30 * unit;
const stroke = 34; // font units, as in the icon script
const half = (stroke / 2) * scale;
// The word's box in splash units (ink plus the stroke), and the sparkle's.
const word = { x: tx + minX * scale - half, y: ty - maxY * scale - half, w: inkW * scale + 2 * half, h: inkH * scale + 2 * half };
const round = (n) => Math.round(n * 10) / 10;
const letters = glyphs.map((g) => ({
  d: g.d,
  ox: round(g.ox),
  oy: round(g.oy),
  // Each letter's own box in splash units, for letters that move on their own.
  x: round(tx + g.box.minX * scale - half),
  y: round(ty - g.box.maxY * scale - half),
  w: round((g.box.maxX - g.box.minX) * scale + 2 * half),
  h: round((g.box.maxY - g.box.minY) * scale + 2 * half),
}));
const out = `// Generated by make-wordmark.mjs from public/fonts/parisienne-400.woff2 (Parisienne, SIL OFL 1.1).
// The launch image's "kiriya" and sparkle (scripts/make-app-icon.mjs, art(2732, { widthShare: 0.3 })),
// in the launch image's own units (a 2732 square drawn aspect-fill), so the opening's first frame is
// the native splash, to the point.
export const SPLASH = 2732;
export const WORD = ${JSON.stringify({ tx: round(tx), ty: round(ty), scale: +scale.toFixed(5), stroke, box: { x: round(word.x), y: round(word.y), w: round(word.w), h: round(word.h) } })};
export const SPARKLE = ${JSON.stringify({ x: round(sx), y: round(sy), unit: +unit.toFixed(4), d: "M0-46Q8-8 46 0 8 8 0 46-8 8-46 0-8-8 0-46Z" })};
export const LETTERS = ${JSON.stringify(letters)};
`;
await writeFile(path.resolve("src/shared/opening/wordmark.js"), out);
console.log("wrote wordmark.js", out.length, "bytes", JSON.stringify(word));
