const SG_DAY = new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Singapore" });
function day(offset, now = new Date()) {
  const base = new Date(`${SG_DAY.format(now)}T12:00:00+08:00`);
  base.setUTCDate(base.getUTCDate() + offset);
  return SG_DAY.format(base);
}
const at = (offset, time = "10:00") => `${day(offset)}T${time}:00+08:00`;
const ago = (hours) => new Date(Date.now() - hours * 3600_000).toISOString();

